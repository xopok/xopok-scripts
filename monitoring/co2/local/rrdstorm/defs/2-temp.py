from rrd_dsl import GraphBuilder


def build_graph(rrd_file):
    g = GraphBuilder(rrd_file)

    ds1 = g.def_ds("ds1", "co2")
    ds1kid = g.def_ds("ds1kid", "co2kid")
    ds4 = g.def_ds("ds4", "humconv")
    ds5 = g.def_ds("ds5", "tempint")
    ds5k = g.def_ds("ds5k", "tempkid")
    ds6 = g.def_ds("ds6", "humint")
    ds6k = g.def_ds("ds6k", "humkid")
    ds7 = g.def_ds("ds7", "tempout")
    ds72 = g.def_ds("ds72", "tempout2")
    ds7min = g.def_ds("ds7min", "tempout", "MIN")
    ds7max = g.def_ds("ds7max", "tempout", "MAX")
    ds8 = g.def_ds("ds8", "humout")

    scaled_ds4 = g.cdef("scaled_ds4", ds4 * 20)
    scaled_ds5 = g.cdef("scaled_ds5", ds5 * 20)
    scaled_ds5k = g.cdef("scaled_ds5k", ds5k * 20)
    scaled_ds6 = g.cdef("scaled_ds6", ds6 * 20)
    scaled_ds6k = g.cdef("scaled_ds6k", ds6k * 20)
    scaled_ds7 = g.cdef("scaled_ds7", ds7 * 20)
    scaled_ds72 = g.cdef("scaled_ds72", ds72 * 20)
    scaled_ds7min = g.cdef("scaled_ds7min", ds7min * 20)
    scaled_ds7max = g.cdef("scaled_ds7max", ds7max * 20)
    scaled_ds8 = g.cdef("scaled_ds8", ds8 * 20)

    g.args.append("AREA:1200#634d21")
    g.args.append("AREA:800#495217")
    g.args.append("AREA:400#3e4d3e")

    g.line(1, scaled_ds5k, "FEE12B", "TKid ")
    g.gprint("ds5k", "%3.1lf", "LAST")
    g.line(1, scaled_ds5, "a0a0a0", "TInt ")
    g.gprint("ds5", "%3.1lf", "LAST")
    g.line(1, scaled_ds6k, "B3F2FF", "HumKid ")
    g.gprint("ds6k", "%3.1lf", "LAST")
    g.line(1, scaled_ds6, "00ACCF", "HumInt ")
    g.gprint("ds6", "%3.1lf", "LAST")
    g.line(2, ds1, "8B9AFE", "CO2")
    g.gprint("ds1", "%4.0lf\\n", "LAST")
    g.line(1, scaled_ds7, "309030", "TWest")
    g.gprint("ds7", "%3.1lf", "LAST")
    g.line(1, scaled_ds72, "FF7F00", "TEast")
    g.gprint("ds72", "%3.1lf", "LAST")
    g.line(1, scaled_ds8, "00CF6F", "HumWest")
    g.gprint("ds8", "%3.1lf", "LAST")
    g.line(1, scaled_ds7min, "0000FF")
    g.line(1, scaled_ds7max, "ff0000")
    g.line(1, scaled_ds4, "ffffff", "HumConv", ":dashes=4,2")
    g.gprint("ds4", "%3.1lf\\n", "LAST")
    g.line(2, ds1kid, "a9f573", "CO2Kid")
    g.gprint("ds1kid", "%4.0lf\\n", "LAST")

    return g.compile()
