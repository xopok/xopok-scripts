from rrd_dsl import GraphBuilder


def build_graph(rrd_file):
    g = GraphBuilder(rrd_file)

    ar = g.def_ds("ar", "ar")
    aw = g.def_ds("aw", "aw")
    ars = g.def_ds("ars", "ars")
    aws = g.def_ds("aws", "aws")
    br = g.def_ds("br", "cr")
    bw = g.def_ds("bw", "cw")
    brs = g.def_ds("brs", "crs")
    bws = g.def_ds("bws", "cws")
    sr = g.def_ds("sr", "br")
    sw = g.def_ds("sw", "bw")
    srs = g.def_ds("srs", "brs")
    sws = g.def_ds("sws", "bws")

    nbr = g.cdef("nbr", br * -1)
    nbw = g.cdef("nbw", bw * -1)
    snbrs = g.cdef("snbrs", (brs * -1) / 2048 * 16)
    snbws = g.cdef("snbws", (bws * -1) / 2048 * 16)
    sars = g.cdef("sars", ars / 2048 * 16)
    saws = g.cdef("saws", aws / 2048 * 16)
    arkb = g.cdef("arkb", ars / 2)
    awkb = g.cdef("awkb", aws / 2)
    brkb = g.cdef("brkb", brs / 2)
    bwkb = g.cdef("bwkb", bws / 2)
    srkb = g.cdef("srkb", srs / 2)
    swkb = g.cdef("swkb", sws / 2)

    g.line(1, ar, "54EC48", "HDD1 avg r/s")
    g.args.append("GPRINT:ar:AVERAGE:%.2lf")
    g.line(1, aw, "EA644A", "w/s")
    g.args.append("GPRINT:aw:AVERAGE:%.2lf")
    g.line(2, sars, "24BC14", "rK/s")
    g.args.append("GPRINT:arkb:AVERAGE:%.2lf")
    argb = g.cdef("argb", arkb / 1024 / 1024)
    g.vdef("totargb", "argb,TOTAL")
    g.args.append("GPRINT:totargb:Sum%.2lf GiB")
    g.line(2, saws, "CC3118", "wK/s")
    g.args.append("GPRINT:awkb:AVERAGE:%.2lf")
    awgb = g.cdef("awgb", awkb / 1024 / 1024)
    g.vdef("totawgb", "awgb,TOTAL")
    g.args.append("GPRINT:totawgb:Sum%.2lf GiB\\n")

    g.line(1, nbr, "54EC48", "HDD2 avg r/s")
    g.args.append("GPRINT:br:AVERAGE:%.2lf")
    g.line(1, nbw, "EA644A", "w/s")
    g.args.append("GPRINT:bw:AVERAGE:%.2lf")
    g.line(2, snbrs, "24BC14", "rK/s")
    g.args.append("GPRINT:brkb:AVERAGE:%.2lf")
    brgb = g.cdef("brgb", brkb / 1024 / 1024)
    g.vdef("totbrgb", "brgb,TOTAL")
    g.args.append("GPRINT:totbrgb:Sum%.2lf GiB")
    g.line(2, snbws, "CC3118", "wK/s")
    g.args.append("GPRINT:bwkb:AVERAGE:%.2lf")
    bwgb = g.cdef("bwgb", bwkb / 1024 / 1024)
    g.vdef("totbwbb", "bwgb,TOTAL")
    g.args.append("GPRINT:totbwbb:Sum%.2lf GiB\\n")

    g.args.append("GPRINT:sr:AVERAGE:SSD avg r/s %.2lf")
    g.args.append("GPRINT:sw:AVERAGE:w/s %.2lf")
    g.args.append("GPRINT:srkb:AVERAGE:| rK/s %.2lf")
    srgb = g.cdef("srgb", srkb / 1024 / 1024)
    g.vdef("totsrgb", "srgb,TOTAL")
    g.args.append("GPRINT:totsrgb:Sum%.2lf GiB")
    g.args.append("GPRINT:swkb:AVERAGE:| wK/s %.2lf")
    swgb = g.cdef("swgb", swkb / 1024 / 1024)
    g.vdef("totswbb", "swgb,TOTAL")
    g.args.append("GPRINT:totswbb:Sum%.2lf GiB\\n")

    g.args.append("HRULE:0#FFFFFF")

    return g.compile()
